#!/usr/bin/env node
// Generates CSS custom properties and type classes from tokens.json.
// Usage: node build.mjs [outFile]  (default: ../../apps/web/src/styles/tokens.css relative to this file,
// or ./src/styles/tokens.css relative to cwd when run from apps/web)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, "tokens.json"), "utf8"));

const cwdTarget = resolve(process.cwd(), "src/styles/tokens.css");
const defaultTarget = existsSync(resolve(process.cwd(), "package.json"))
  ? cwdTarget
  : resolve(here, "../../apps/web/src/styles/tokens.css");
const out = process.argv[2] ? resolve(process.argv[2]) : defaultTarget;

const value = (v) =>
  typeof v === "string" ? v.replace(/^\{([^}]+)\}$/, (_, a) => `var(--${a})`) : String(v);

const lines = [];
lines.push("/* Generated by packages/design-tokens/build.mjs from tokens.json. Do not edit. */", "", ":root {");
lines.push("  /* color */");
for (const t of tokens.color?.tokens ?? []) lines.push(`  --${t.name}: ${value(t.value)};`);
lines.push("", "  /* type families */");
for (const [k, v] of Object.entries(tokens.type?.families ?? {})) lines.push(`  --font-${k}: ${v};`);
lines.push("", "  /* spacing */");
for (const t of tokens.spacing?.tokens ?? []) lines.push(`  --${t.name}: ${value(t.value)};`);
lines.push("", "  /* radius */");
for (const t of tokens.radius?.tokens ?? []) lines.push(`  --${t.name}: ${value(t.value)};`);
if (tokens.shadow?.tokens?.length) {
  lines.push("", "  /* shadow */");
  for (const t of tokens.shadow.tokens) lines.push(`  --${t.name}: ${value(t.value)};`);
}
lines.push("}", "");

for (const group of tokens.type?.groups ?? []) {
  lines.push(`/* ${group.name} */`);
  for (const s of group.styles) {
    lines.push(`.${s.name} {`);
    lines.push(`  font-family: var(--font-${group.family ?? "sans"});`);
    if (s.fontSize) lines.push(`  font-size: ${s.fontSize};`);
    if (s.lineHeight != null) lines.push(`  line-height: ${s.lineHeight};`);
    if (s.fontWeight != null) lines.push(`  font-weight: ${s.fontWeight};`);
    if (s.letterSpacing) lines.push(`  letter-spacing: ${s.letterSpacing};`);
    if (/eyebrow/.test(s.name)) lines.push(`  text-transform: uppercase;`);
    lines.push("}");
  }
  lines.push("");
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join("\n"));
console.log(`tokens: wrote ${out}`);
